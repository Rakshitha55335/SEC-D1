# Python program to perform operations on a list

numbers = [10, 20, 30, 40, 50]

print("Original list:", numbers)

# i. Addition
numbers.append(60)
print("After addition:", numbers)

# ii. Insertion
numbers.insert(2, 25)
print("After insertion:", numbers)

# iii. Slicing
print("Sliced list:", numbers[1:5])