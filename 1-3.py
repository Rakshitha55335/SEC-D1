# Python program to add and multiply complex numbers

# Input two complex numbers
c1 = complex(input("Enter first complex number (a+bj): "))
c2 = complex(input("Enter second complex number (a+bj): "))

# Addition
addition = c1 + c2

# Multiplication
multiplication = c1 * c2

# Display results
print("\nFirst Complex Number:", c1)
print("Second Complex Number:", c2)
print("Addition:", addition)
print("Multiplication:", multiplication)